-- Drop redundant partial index on moments.s2_cell_id.
--
-- Background: migration 025 created idx_moments_public_s2_cell_id with the
-- predicate `WHERE privacy_level = 'public'`. Migration 026 then created
-- idx_moments_non_private_s2_cell_id with the predicate
-- `WHERE privacy_level <> 'private'`.
--
-- PrivacyLevel is a closed enum with exactly two values: 'public' | 'private'
-- (spec/api_spec_types.md:33). Therefore:
--     privacy_level = 'public'  <=>  privacy_level <> 'private'
-- The two predicates match identical row sets, so the indexes are redundant.
--
-- The non-private index (026) is retained because it is the more recent one and
-- its naming conveys the intent ("non-private", i.e. visible to non-owners)
-- more clearly than "public" does under a binary enum. The plain unfiltered
-- idx_moments_s2_cell_id from migration 025 is also retained for queries that
-- do not filter by privacy (e.g. owner listing their own moments).
DROP INDEX IF EXISTS idx_moments_public_s2_cell_id;
