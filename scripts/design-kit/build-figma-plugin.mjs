#!/usr/bin/env node
/**
 * 生成 Figma 本地开发插件：把设计规格（spec.json）与插件运行时打包成
 * docs/design-kit/figma-plugin/code.js，供 Figma 桌面端「导入插件」直接运行。
 * 用法：node scripts/design-kit/build-figma-plugin.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SPEC = join(ROOT, '.workwork', 'design-kit', 'spec', 'spec.json');
const RUNTIME = join(ROOT, 'scripts', 'design-kit', 'figma-runtime.js');
const OUT = join(ROOT, 'docs', 'design-kit', 'figma-plugin');

let commit = 'dev';
try { commit = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim(); } catch (e) {}

let spec;
if (existsSync(SPEC)) {
  spec = JSON.parse(readFileSync(SPEC, 'utf8'));
} else if (existsSync(join(OUT, 'code.js'))) {
  const existingCode = readFileSync(join(OUT, 'code.js'), 'utf8');
  const startIdx = existingCode.indexOf('var SPEC = ');
  const endIdx = existingCode.indexOf(';\n', startIdx);
  if (startIdx >= 0 && endIdx > startIdx) {
    const jsonStr = existingCode.slice(startIdx + 'var SPEC = '.length, endIdx).trim();
    spec = JSON.parse(jsonStr);
  } else {
    throw new Error('Cannot locate existing SPEC in code.js');
  }
} else {
  throw new Error('Neither spec.json nor code.js exists to build plugin');
}
const runtime = readFileSync(RUNTIME, 'utf8');

spec.meta.builtAt = new Date().toISOString();
spec.meta.commit = commit;

const code = '// HotSpot Design Kit — generated by scripts/design-kit/build-figma-plugin.mjs\n' +
  '// 数据来源：docs/design-kit/spec/spec.json（由 capture-screens + build-design-spec 生成）\n' +
  'var SPEC = ' + JSON.stringify(spec) + ';\n' + runtime;

const manifest = {
  name: 'HotSpot Design Kit',
  id: '202611120000000001',
  api: '1.0.0',
  main: 'code.js',
  editorType: ['figma'],
  networkAccess: { allowedDomains: ['none'] }
};

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(join(OUT, 'code.js'), code);
console.log('plugin written:', OUT);
console.log('code.js bytes', code.length, 'screens', spec.meta.screenCount, 'variables', spec.variables.length);
