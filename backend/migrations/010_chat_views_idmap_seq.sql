-- ============================================================
-- 010_chat_views_idmap_seq.sql
-- 为聊天消息提供可查询视图，并为 ID Map 添加顺序游标列
-- ============================================================

-- ─── 私聊/群聊消息视图（面向查询层，封装分区表）───────────
CREATE OR REPLACE VIEW private_messages AS
SELECT
    message_id,
    chat_id,
    sender_id,
    receiver_id,
    message_type,
    content,
    metadata,
    share_code,
    reply_to_id,
    is_recalled,
    recalled_at,
    edited_at,
    reaction_counts,
    sent_at
FROM private_messages_partitioned;

CREATE OR REPLACE VIEW group_messages AS
SELECT
    message_id,
    group_id,
    sender_id,
    message_type,
    content,
    metadata,
    share_code,
    reply_to_id,
    at_users AS mentions,
    is_recalled,
    recalled_at,
    recalled_by,
    edited_at,
    reaction_counts,
    read_count,
    sent_at
FROM group_messages_partitioned;

-- ─── ID Map 顺序游标列（供 BloomFilter 暖机高效扫描）────────
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'private_message_id_map'
          AND column_name = 'row_id'
    ) THEN
        ALTER TABLE private_message_id_map
            ADD COLUMN row_id BIGINT GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END$$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_private_message_id_map_row_id
    ON private_message_id_map(row_id);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'group_message_id_map'
          AND column_name = 'row_id'
    ) THEN
        ALTER TABLE group_message_id_map
            ADD COLUMN row_id BIGINT GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END$$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_group_message_id_map_row_id
    ON group_message_id_map(row_id);
