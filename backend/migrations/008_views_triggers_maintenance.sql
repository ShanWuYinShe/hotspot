-- ─── 过期数据清理（通用函数）──────────────────────────────

-- 清理过期验证码
CREATE OR REPLACE FUNCTION cleanup_expired_verification_codes(p_older_than INTERVAL DEFAULT '1 day')
RETURNS INTEGER AS $$
DECLARE
    affected INTEGER;
BEGIN
    DELETE FROM verification_codes WHERE expires_at < NOW() - p_older_than;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;

-- 清理过期密码重置
CREATE OR REPLACE FUNCTION cleanup_expired_password_resets(p_older_than INTERVAL DEFAULT '1 day')
RETURNS INTEGER AS $$
DECLARE
    affected INTEGER;
BEGIN
    DELETE FROM password_resets WHERE expires_at < NOW() - p_older_than;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;

-- 清理过期上传会话
CREATE OR REPLACE FUNCTION cleanup_expired_upload_sessions(p_older_than INTERVAL DEFAULT '1 day')
RETURNS INTEGER AS $$
DECLARE
    affected INTEGER;
BEGIN
    DELETE FROM upload_sessions WHERE expires_at < NOW() - p_older_than AND status IN ('pending', 'processing');
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;

-- 清理过期分享
CREATE OR REPLACE FUNCTION cleanup_expired_shares(p_older_than INTERVAL DEFAULT '0 seconds')
RETURNS INTEGER AS $$
DECLARE
    affected INTEGER;
BEGIN
    DELETE FROM shares WHERE expires_at IS NOT NULL AND expires_at < NOW() - p_older_than;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;

-- 清理过期邀请
CREATE OR REPLACE FUNCTION cleanup_expired_invites(p_older_than INTERVAL DEFAULT '0 seconds')
RETURNS INTEGER AS $$
DECLARE
    affected INTEGER;
BEGIN
    UPDATE group_invites SET status = 'rejected'
    WHERE status = 'pending' AND expires_at IS NOT NULL AND expires_at < NOW() - p_older_than;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;

-- 清理过期会话
CREATE OR REPLACE FUNCTION cleanup_expired_sessions(p_older_than INTERVAL DEFAULT '0 seconds')
RETURNS INTEGER AS $$
DECLARE
    affected INTEGER;
BEGIN
    DELETE FROM sessions WHERE expires_at < NOW() - p_older_than;
    GET DIAGNOSTICS affected = ROW_COUNT;
    RETURN affected;
END;
$$ LANGUAGE plpgsql;

-- 一键全量清理（由 pg_cron 定期执行）
CREATE OR REPLACE FUNCTION run_cleanup_maintenance()
RETURNS void AS $$
BEGIN
    PERFORM cleanup_expired_verification_codes();
    PERFORM cleanup_expired_password_resets();
    PERFORM cleanup_expired_upload_sessions();
    PERFORM cleanup_expired_shares();
    PERFORM cleanup_expired_invites();
    PERFORM cleanup_expired_sessions();
    PERFORM run_partition_maintenance();
    RAISE NOTICE 'Maintenance complete at %', NOW();
END;
$$ LANGUAGE plpgsql;
