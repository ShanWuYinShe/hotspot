-- ─── 触发器函数 ─────────────────────────────────────────────

-- 关注统计同步
CREATE OR REPLACE FUNCTION trg_follows_after_insert() RETURNS TRIGGER AS $$
BEGIN
    PERFORM apply_user_stats_delta(NEW.follower_id, p_following_delta := 1);
    PERFORM apply_user_stats_delta(NEW.following_id, p_followers_delta := 1);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION trg_follows_after_delete() RETURNS TRIGGER AS $$
BEGIN
    PERFORM apply_user_stats_delta(OLD.follower_id, p_following_delta := -1);
    PERFORM apply_user_stats_delta(OLD.following_id, p_followers_delta := -1);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

