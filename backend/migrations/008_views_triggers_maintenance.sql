-- ─── 聚合视图 ──────────────────────────────────────────────

-- 用户统计（从 bucket 聚合）
CREATE OR REPLACE VIEW user_stats AS
SELECT
    user_id,
    SUM(moments_count)::INTEGER   AS moments_count,
    SUM(friends_count)::INTEGER   AS friends_count,
    SUM(following_count)::INTEGER AS following_count,
    SUM(followers_count)::INTEGER AS followers_count,
    SUM(groups_count)::INTEGER    AS groups_count
FROM user_stats_buckets
GROUP BY user_id;

-- 群组统计（从 bucket 聚合）
CREATE OR REPLACE VIEW group_stats AS
SELECT
    group_id,
    SUM(member_count)::INTEGER    AS member_count,
    SUM(message_count)::INTEGER   AS message_count
FROM group_stats_buckets
GROUP BY group_id;

-- 瞬间统计（从 bucket 聚合）
CREATE OR REPLACE VIEW moment_stats AS
SELECT
    moment_id,
    SUM(likes_count)::INTEGER     AS likes_count,
    SUM(comments_count)::INTEGER  AS comments_count,
    SUM(shares_count)::INTEGER    AS shares_count,
    SUM(reactions_count)::INTEGER AS reactions_count
FROM moment_stats_buckets
GROUP BY moment_id;

-- 瞬间视图（分区表 + 统计，供 FROM moments 查询）
CREATE OR REPLACE VIEW moments AS
SELECT
    m.moment_id, m.user_id, m.description, m.mentions, m.location, m.location_name,
    m.privacy_level, m.created_at, m.updated_at, m.deleted_at,
    0::INTEGER AS view_count,
    COALESCE(ms.likes_count, 0)::INTEGER AS like_count,
    COALESCE(ms.comments_count, 0)::INTEGER AS comments_count,
    COALESCE(ms.shares_count, 0)::INTEGER AS share_count
FROM moments_partitioned m
LEFT JOIN moment_stats ms ON ms.moment_id = m.moment_id;

-- 评论统计（从 bucket 聚合）
CREATE OR REPLACE VIEW comment_stats AS
SELECT
    comment_id,
    SUM(likes_count)::INTEGER     AS likes_count,
    SUM(replies_count)::INTEGER   AS replies_count
FROM comment_stats_buckets
GROUP BY comment_id;

-- ─── 统计 Delta 函数（高并发 bucket 写入）──────────────────

CREATE OR REPLACE FUNCTION apply_user_stats_delta(
    p_user_id BIGINT,
    p_moments_delta   INTEGER DEFAULT 0,
    p_friends_delta   INTEGER DEFAULT 0,
    p_following_delta INTEGER DEFAULT 0,
    p_followers_delta INTEGER DEFAULT 0,
    p_groups_delta    INTEGER DEFAULT 0
) RETURNS void AS $$
DECLARE
    v_bucket SMALLINT := bucket_for_key(p_user_id);
BEGIN
    INSERT INTO user_stats_buckets (user_id, bucket_id, moments_count, friends_count, following_count, followers_count, groups_count, updated_at)
    VALUES (p_user_id, v_bucket, GREATEST(0, p_moments_delta), GREATEST(0, p_friends_delta), GREATEST(0, p_following_delta), GREATEST(0, p_followers_delta), GREATEST(0, p_groups_delta), NOW())
    ON CONFLICT (user_id, bucket_id) DO UPDATE SET
        moments_count   = CASE WHEN p_moments_delta >= 0 THEN user_stats_buckets.moments_count + p_moments_delta ELSE GREATEST(0, user_stats_buckets.moments_count + p_moments_delta) END,
        friends_count   = CASE WHEN p_friends_delta >= 0 THEN user_stats_buckets.friends_count + p_friends_delta ELSE GREATEST(0, user_stats_buckets.friends_count + p_friends_delta) END,
        following_count = CASE WHEN p_following_delta >= 0 THEN user_stats_buckets.following_count + p_following_delta ELSE GREATEST(0, user_stats_buckets.following_count + p_following_delta) END,
        followers_count = CASE WHEN p_followers_delta >= 0 THEN user_stats_buckets.followers_count + p_followers_delta ELSE GREATEST(0, user_stats_buckets.followers_count + p_followers_delta) END,
        groups_count    = CASE WHEN p_groups_delta >= 0 THEN user_stats_buckets.groups_count + p_groups_delta ELSE GREATEST(0, user_stats_buckets.groups_count + p_groups_delta) END,
        updated_at      = NOW();
END;
$$ LANGUAGE plpgsql;

